def calculate_bv(unit: AbstractUnit) -> int:
    """Calculate Battle Value 2.0. Checks MUL cache first, then dispatches."""
    # Check cached MUL BV first
    cached = _lookup_bv(unit)
    if cached is not None:
        return cached

    from ..models.mech import BattleMech
    from ..models.vehicle import CombatVehicle
    from ..models.battle_armor import BattleArmor
    from ..models.aero import AeroSpaceFighter

    if isinstance(unit, BattleMech):
        return _calculate_mech_bv(unit)
    elif isinstance(unit, CombatVehicle):
        return _calculate_vehicle_bv(unit)
    elif isinstance(unit, BattleArmor):
        return _calculate_ba_bv(unit)
    elif isinstance(unit, AeroSpaceFighter):
        return _calculate_aero_bv(unit)
    return 0


def _calculate_mech_bv(unit: BattleMech) -> int:
    """Calculate BV 2.0 for a BattleMech."""
    dbr = _mech_defensive_br(unit)
    obr = _mech_offensive_br(unit)
    final_bv = round(dbr + obr)

    # Cockpit modifiers (Tech Manual p. 303)
    # Small Cockpit or Torso-Mounted Cockpit: ×0.95
    if unit.is_equipped_with("smcp") or unit.is_equipped_with("tmcp"):
        final_bv = round(final_bv * 0.95)

    return max(final_bv, 1)


# ── Defensive Battle Rating ──────────────────────────────────────────────────

def _mech_defensive_br(unit: BattleMech) -> float:
    """Compute Defensive Battle Rating for a BattleMech."""
    # 1. Armor Factor
    total_armor = sum(unit.armor.values())
    # Torso-Mounted Cockpit adds CT front+rear armor (MegaMek addTorsoMountedCockpit)
    if unit.is_equipped_with("tmcp"):
        total_armor += unit.armor.get("CT", 0) + unit.armor.get("CTR", 0)
    armor_mod = _detect_armor_modifier(unit)
    armor_factor = total_armor * 2.5 * armor_mod

    # 2. Internal Structure Factor
    struct = unit.structure()
    total_is = sum(struct.values())
    is_mod = _detect_is_modifier(unit)
    engine_mod = _detect_engine_modifier(unit)
    is_factor = total_is * 1.5 * is_mod * engine_mod

    # 3. Gyro
    gyro_mod = _detect_gyro_modifier(unit)
    gyro = unit.tonnage * gyro_mod

    # 4. Defensive Equipment BV
    defensive_equip_bv = _defensive_equipment_bv(unit)

    # 5. Ammo penalties (simplified)
    ammo_penalty = _ammo_explosion_penalty(unit)

    subtotal = armor_factor + is_factor + gyro + defensive_equip_bv - ammo_penalty
    if subtotal < 1:
        subtotal = 1.0

    # 6. Defensive Factor
    tmm = _max_tmm(unit)
    df = _defensive_factor(tmm)

    return subtotal * df


def _defensive_equipment_bv(unit: BattleMech) -> float:
    """Sum BV of defensive equipment."""
    from ..models.data_store import DataStore
    total = 0
    for e in unit.equipment:
        if e.equipment_key in _DEFENSIVE_EQUIPMENT_KEYS:
            try:
                eq = DataStore.equipment(e.equipment_key)
                total += eq.bv
            except KeyError:
                pass
    return total


def _ammo_explosion_penalty(unit: BattleMech) -> float:
    """
    Ammo explosion penalty: 15 per ton of explosive ammo.

    Simplified — does not track ammo bin locations.
    Clan mechs have free CASE (assumed protected except CT/legs/head).
    """
    from ..models.data_store import DataStore

    has_freecase = unit.is_equipped_with("freecase")
    has_case = unit.is_equipped_with("case") or unit.is_equipped_with("case2")

    # RAC, Gauss, HVAC ammo types are NOT explosive per MegaMek
    _NON_EXPLOSIVE_AMMO = {"RAC", "Gauss", "HAG"}

    # Count ammo tons (uses = tons per mtf_parser.py:240)
    total_ammo_tons = 0.0
    for e in unit.equipment:
        try:
            eq = DataStore.equipment(e.equipment_key)
        except KeyError:
            continue
        if eq.shots_per_ton > 0 and eq.bv > 0:
            if e.subtype not in _NON_EXPLOSIVE_AMMO:
                total_ammo_tons += e.uses if e.uses else 1.0

    if has_freecase:
        # Clan: free CASE protects all torso locations
        return 0.0
    elif has_case:
        # IS with CASE: reduced penalty
        return total_ammo_tons * 7.5
    else:
        # IS without CASE: full penalty
        return total_ammo_tons * 15.0


# ── Offensive Battle Rating ──────────────────────────────────────────────────

def _mech_offensive_br(unit: BattleMech) -> float:
    """Compute Offensive Battle Rating for a BattleMech."""
    from ..models.data_store import DataStore

    # Heat sink capacity
    heat_sink_capacity = unit.sinks * (2 if unit.has_dhs else 1)
    heat_efficiency = 6 + heat_sink_capacity - _movement_heat(unit)

    # Build weapon list with BV and heat
    weapon_entries = []
    for w in unit.weapons:
        try:
            wp = DataStore.weapon(w.weapon_key)
            base_bv = wp.bv
            heat = _weapon_heat(wp, w.one_shot)

            # Apply modifiers
            modified_bv = base_bv

            # Artemis IV / V FCS: +20% for missile launchers
            if w.fcs in ("aiv", "av") and wp.useAmmo:
                modified_bv = base_bv * 1.2

            # Targeting Computer: +25%
            if unit.is_equipped_with("tc") and wp.useTC:
                modified_bv = base_bv * 1.25

            # Rear-firing: half BV
            if w.location.startswith("(R)"):
                modified_bv *= 0.5

            weapon_entries.append({
                "bv": modified_bv,
                "heat": heat,
                "key": w.weapon_key,
                "ammo_type": wp.useAmmo,
            })
        except KeyError:
            continue

    # Ammo BV (capped at weapon BV per weapon model)
    ammo_bv = _calculate_ammo_bv(unit, weapon_entries)

    # Separate no-heat weapons
    no_heat_weapons = [w for w in weapon_entries if w["heat"] == 0]
    heat_weapons = [w for w in weapon_entries if w["heat"] > 0]

    wbr = 0.0

    # Step 1: Add all no-heat weapons at full BV
    for w in no_heat_weapons:
        wbr += w["bv"]

    # Step 2: Add ammo BV
    wbr += ammo_bv

    # Step 3: Heat efficiency check
    total_weapon_heat = sum(w["heat"] for w in weapon_entries)

    if total_weapon_heat <= heat_efficiency:
        # All weapons at full BV
        for w in heat_weapons:
            wbr += w["bv"]
    else:
        # Heat efficiency loop
        heat_weapons.sort(key=lambda w: (-w["bv"], w["heat"]))
        running_heat = 0
        for i, w in enumerate(heat_weapons):
            if running_heat < heat_efficiency:
                # Full BV
                wbr += w["bv"]
                running_heat += w["heat"]
            else:
                # Half BV for remaining
                wbr += w["bv"] * 0.5

    # Step 8: Add tonnage with TSM multiplier (MegaMek: weight × modifier)
    tsm_mult = 1.0
    if unit.is_equipped_with("tsm"):
        tsm_mult = 1.5
    wbr += unit.tonnage * tsm_mult

    # Speed Factor
    sf = _speed_factor(unit.run_mp, unit.jump_mp)

    return wbr * sf


def _weapon_heat(wp, one_shot: bool) -> float:
    """Calculate adjusted weapon heat for BV purposes."""
    heat = wp.heat_value()

    # Ultra autocannons: ×2
    if wp.type == "B" and wp.useR and wp.useR > 1:
        # RAC: rotary autocannon — BV heat = 6 per MegaMek (not raw heat × 6)
        if wp.useR >= 5:
            heat = 6
        else:
            heat *= 2

    # Streak SRMs: ×½
    if "streak" in wp.key.lower() or "ssrm" in wp.key.lower():
        heat *= 0.5

    # One-shot: ×¼
    if one_shot or wp.has_special("os"):
        heat *= 0.25

    return heat


def _calculate_ammo_bv(unit: BattleMech, weapon_entries: list[dict]) -> float:
    """Calculate total ammo BV, capped per weapon model.

    MTF parser stores ammo tons in `uses` field (see mtf_parser.py:240).
    Each ton = one crit slot of ammo.
    """
    from ..models.data_store import DataStore
    from collections import defaultdict

    # Sum weapon BV per model (for capping)
    weapon_bv_by_ammo: dict[str, float] = defaultdict(float)
    for w in weapon_entries:
        ammo_type = w["ammo_type"]
        if ammo_type:
            weapon_bv_by_ammo[ammo_type] += w["bv"]

    # Sum ammo BV from equipment
    ammo_bv_by_type: dict[str, float] = defaultdict(float)
    for e in unit.equipment:
        try:
            eq = DataStore.equipment(e.equipment_key)
        except KeyError:
            continue
        if eq.shots_per_ton > 0 and eq.bv > 0:
            # uses = tons of ammo (mtf_parser stores tons in uses field)
            tons = e.uses if e.uses else 1.0
            ammo_bv_by_type[e.subtype] += eq.bv * tons

    # Cap each ammo type's BV at the weapon BV for that type
    total_ammo_bv = 0.0
    for ammo_type, bv in ammo_bv_by_type.items():
        capped = min(bv, weapon_bv_by_ammo.get(ammo_type, 0))
        total_ammo_bv += capped

    return total_ammo_bv


