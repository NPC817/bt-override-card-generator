# Generic ammo BV helper (works with any unit type)
# ═══════════════════════════════════════════════════════════════════════════════


def _calc_ammo_bv_generic(unit, weapon_bv_by_ammo: dict) -> float:
    """Calculate ammo BV for vehicles, BA, and aero."""
    from ..models.data_store import DataStore
    from collections import defaultdict

    ammo_bv_by_type = defaultdict(float)
    for e in unit.equipment:
        try:
            eq = DataStore.equipment(e.equipment_key)
        except KeyError:
            continue
        if eq.shots_per_ton > 0 and eq.bv > 0:
            tons = e.uses if e.uses else 1.0
            ammo_bv_by_type[e.subtype] += eq.bv * tons

    total = 0.0
    for ammo_type, bv in ammo_bv_by_type.items():
        total += min(bv, weapon_bv_by_ammo.get(ammo_type, 0))
    return total
