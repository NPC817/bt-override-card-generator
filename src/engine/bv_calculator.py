# ── Speed Factor Table (Tech Manual p. 315) ──────────────────────────────────

_SPEED_FACTOR_TABLE = {
    0: 0.44,  1: 0.54,  2: 0.65,  3: 0.77,  4: 0.88,
    5: 1.00,  6: 1.12,  7: 1.24,  8: 1.37,  9: 1.50,
    10: 1.63, 11: 1.76, 12: 1.89, 13: 2.02, 14: 2.16,
    15: 2.30, 16: 2.44, 17: 2.58, 18: 2.72, 19: 2.86,
    20: 3.00, 21: 3.15, 22: 3.29, 23: 3.44, 24: 3.59,
    25: 3.74,
}


def _speed_factor(run_mp: int, jump_mp: int = 0) -> float:
    """Compute Speed Factor from run MP and jump MP."""
    speed_input = run_mp + math.ceil(jump_mp / 2)
    if speed_input in _SPEED_FACTOR_TABLE:
        return _SPEED_FACTOR_TABLE[speed_input]
    # Formula for values beyond table: SF = (1 + ((input - 5) / 10)) ^ 1.2
    sf = (1 + (speed_input - 5) / 10) ** 1.2
    return round(sf, 2)


# ── Defensive Factor Table ───────────────────────────────────────────────────

def _defensive_factor(tmm: int) -> float:
    """Defensive Factor based on highest target movement modifier."""
    table = {
        0: 1.0, 1: 1.1, 2: 1.2, 3: 1.3, 4: 1.4,
        5: 1.5, 6: 1.6, 7: 1.7, 8: 1.8,
    }
    if tmm in table:
        return table[tmm]
    return 1.0 + (tmm / 10.0)


# ── Engine type detection ────────────────────────────────────────────────────

def _detect_engine_modifier(unit: BattleMech) -> float:
    """
    Detect engine type modifier from equipment keys.

    Standard / Compact / ICE / Fuel Cell / Fission: 1.0
    Light:  0.75
    IS XL:  0.50
    Clan XL: 0.75
    """
    equip_keys = {e.equipment_key for e in unit.equipment}

    # Clan XL
    if "cxle" in equip_keys or "cxxle" in equip_keys:
        return 0.75
    # IS XXL (very vulnerable — 0.25)
    if "xxle" in equip_keys:
        return 0.25
    # IS XL
    if "xle" in equip_keys:
        return 0.5
    # Light
    if "lfe" in equip_keys:
        return 0.75
    # Standard / Compact / ICE / Fuel Cell / Fission
    return 1.0


# ── Gyro type detection ──────────────────────────────────────────────────────

def _detect_gyro_modifier(unit: BattleMech) -> float:
    """Gyro type multiplier. Standard/Compact/XL = 0.5, Heavy Duty = 1.0."""
    if unit.is_equipped_with("hdgyro"):
        return 1.0
    return 0.5


# ── IS type detection ────────────────────────────────────────────────────────

def _detect_is_modifier(unit: BattleMech) -> float:
    """Internal Structure type modifier from MegaMek BV calculator.

    Standard/Endo = 1.0, Composite = 0.5, Reinforced = 2.0, Industrial = 0.5.
    """
    if unit.is_equipped_with("reinforced"):
        return 2.0
    if unit.is_equipped_with("composite"):
        return 0.5
    return 1.0


# ── Armor type detection ─────────────────────────────────────────────────────

def _detect_armor_modifier(unit: BattleMech) -> float:
    """Armor type BV modifier from MegaMek armorMultiplier table.

    Reactive/Reflective = 1.5, Hardened = 2.0, Ferro-Lamellor = 1.2,
    Ballistic-Reinforced = 1.5, Heat-Dissipating = 1.1, others = 1.0.
    """
    if unit.is_equipped_with("hardened"):
        return 2.0
    if unit.is_equipped_with("lasrefl") or unit.is_equipped_with("reactive"):
        return 1.5
    if unit.is_equipped_with("ballreinf"):
        return 1.5
    if unit.is_equipped_with("ferolam"):
        return 1.2
    return 1.0


