def _calculate_aero_bv(unit) -> int:
    """Calculate BV 2.0 for an AeroSpace Fighter."""
    dbr = _aero_defensive_br(unit)
    obr = _aero_offensive_br(unit)
    final_bv = round(dbr + obr)
    # Small cockpit: ×0.95
    if unit.is_equipped_with("smcp"):
        final_bv = round(final_bv * 0.95)
    return max(final_bv, 1)


def _aero_defensive_br(unit) -> float:
    from ..models.data_store import DataStore

    # Armor: sum all zones × 2.5
    total_armor = sum(unit.armor.values())
    armor_mod = _detect_armor_modifier(unit)
    armor_factor = total_armor * 2.5 * armor_mod

    # SI: safe_thrust × 2.0 (aero SI = max thrust / safe thrust)
    si = unit.safe_thrust
    si_factor = si * 2.0

    # Defensive equipment
    def_eq_bv = _defensive_equipment_bv(unit)

    # Ammo penalty: -15 per ammo type (not per ton)
    ammo_pen = 0.0
    has_case = unit.is_equipped_with("case") or unit.is_equipped_with("case2")
    has_freecase = unit.is_equipped_with("freecase")
    if not has_case and not has_freecase:
        seen_types = set()
        for e in unit.equipment:
            try:
                eq = DataStore.equipment(e.equipment_key)
            except KeyError:
                continue
            if eq.shots_per_ton > 0 and eq.bv > 0:
                if e.subtype not in seen_types:
                    seen_types.add(e.subtype)
                    ammo_pen += 15

    subtotal = armor_factor + si_factor + def_eq_bv - ammo_pen
    if subtotal < 1:
        subtotal = 1.0

    # Type modifier (no defensive factor for aero)
    is_conv = unit.motive_type == "Conventional"
    type_mod = 1.2 if not is_conv else 1.1
    if unit.is_equipped_with("stealth"):
        type_mod += 0.3

    return subtotal * type_mod


def _aero_offensive_br(unit) -> float:
    from ..models.data_store import DataStore
    from collections import defaultdict

    heat_sink_capacity = unit.sinks * (2 if unit.has_dhs else 1)
    heat_efficiency = 6 + heat_sink_capacity
    if unit.is_equipped_with("stealth"):
        heat_efficiency -= 10

    weapon_entries = []
    for w in unit.weapons:
        try:
            wp = DataStore.weapon(w.weapon_key)
            base_bv = wp.bv
            heat = _weapon_heat(wp, w.one_shot)
            if w.fcs in ("aiv", "av") and wp.useAmmo:
                base_bv *= 1.2
            if unit.is_equipped_with("tc") and wp.useTC:
                base_bv *= 1.25
            weapon_entries.append({"bv": base_bv, "heat": heat, "key": w.weapon_key, "ammo_type": wp.useAmmo})
        except KeyError:
            continue

    weapon_bv_by_ammo = defaultdict(float)
    for w in weapon_entries:
        if w["ammo_type"]:
            weapon_bv_by_ammo[w["ammo_type"]] += w["bv"]

    ammo_bv = _calc_ammo_bv_generic(unit, weapon_bv_by_ammo)

    no_heat = [w for w in weapon_entries if w["heat"] == 0]
    heat_w = [w for w in weapon_entries if w["heat"] > 0]

    wbr = sum(w["bv"] for w in no_heat) + ammo_bv

    total_weapon_heat = sum(w["heat"] for w in weapon_entries)
    if total_weapon_heat <= heat_efficiency:
        for w in heat_w:
            wbr += w["bv"]
    else:
        heat_w.sort(key=lambda w: (-w["bv"], w["heat"]))
        running_heat = 0
        for w in heat_w:
            if running_heat < heat_efficiency:
                wbr += w["bv"]
                running_heat += w["heat"]
            else:
                wbr += w["bv"] * 0.5

    # No weight contribution for aero
    sf = _speed_factor(unit.max_thrust, 0)
    return wbr * sf


