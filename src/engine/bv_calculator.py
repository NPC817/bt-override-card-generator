# ── Movement heat ────────────────────────────────────────────────────────────

def _movement_heat(unit: BattleMech) -> int:
    """Heat generated by running or jumping at max capacity.

    Also handles stealth/electronic warfare systems that reduce heat efficiency
    (they add to movement heat per MegaMek MekBVCalculator).
    """
    # Running: 2 heat for standard fusion
    run_heat = 2
    # Jumping: max(jump_mp, 3) standard, or half with Improved Jump Jets
    if unit.jump_mp > 0:
        if unit.is_equipped_with("ijump"):
            jump_heat = max(unit.jump_mp // 2, 3)
        else:
            jump_heat = max(unit.jump_mp, 3)
    else:
        jump_heat = 0
    movement_heat = max(run_heat, jump_heat)
    # Stealth/electronic warfare systems reduce heat efficiency
    if unit.is_equipped_with("stealth"):
        movement_heat += 10
    # Null-Signature System
    if unit.is_equipped_with("nullsig"):
        movement_heat += 10
    # Void-Signature System
    if unit.is_equipped_with("voidsig"):
        movement_heat += 10
    # Chameleon Light Polarization Shield
    if unit.is_equipped_with("chameleon"):
        movement_heat += 6
    # XXL engines: +4 heat when running (per MegaMek)
    if unit.is_equipped_with("xxle") or unit.is_equipped_with("cxxle"):
        movement_heat += 4
    return movement_heat


# ── Target Movement Modifier ─────────────────────────────────────────────────

def _max_tmm(unit: BattleMech) -> int:
    """Highest possible TMM for defensive factor.

    Stealth/Null-Sig/Chameleon add +2 per MegaMek MekBVCalculator.
    Void-Sig sets minimum TMM of 3.
    """
    from ..utils.math import _tmm
    run_tmm = _tmm(unit.run_mp)
    if unit.jump_mp > 0:
        jump_tmm = _tmm(unit.jump_mp)
        tmm = max(run_tmm, jump_tmm)
    else:
        tmm = run_tmm
    # Stealth/Null-Sig/Chameleon: +2 TMM
    if unit.is_equipped_with("stealth") or unit.is_equipped_with("nullsig"):
        tmm += 2
    if unit.is_equipped_with("chameleon"):
        tmm += 2
    return tmm


