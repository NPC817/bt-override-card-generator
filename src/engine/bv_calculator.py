_VEHICLE_TYPE_MODS = {
    "Tracked": 0.9, "Wheeled": 0.8, "Hover": 0.7,
    "VTOL": 0.7, "WiGE": 0.7,
}


def _calculate_vehicle_bv(unit) -> int:
    """Calculate BV 2.0 for a Combat Vehicle."""
    if unit.tonnage < 5:
        return 0  # Skip tiny vehicles (IS model inaccurate below 5 tons)
    dbr = _vehicle_defensive_br(unit)
    obr = _vehicle_offensive_br(unit)
    return max(round(dbr + obr), 1)


def _vehicle_defensive_br(unit) -> float:
    from ..models.data_store import DataStore

    # Armor: all locations, ×2.5, same armor type modifiers
    total_armor = sum(unit.armor.values())
    armor_mod = _detect_armor_modifier(unit)
    armor_factor = total_armor * 2.5 * armor_mod

    # IS: total IS points × 1.5
    struct = unit.structure()
    total_is = sum(struct.values())
    is_factor = total_is * 1.5

    # Defensive equipment
    def_eq_bv = _defensive_equipment_bv(unit)

    # Ammo penalty (same as mech)
    ammo_pen = _ammo_explosion_penalty(unit)

    subtotal = armor_factor + is_factor + def_eq_bv - ammo_pen
    if subtotal < 1:
        subtotal = 1.0

    # Type modifier
    type_mod = _VEHICLE_TYPE_MODS.get(unit.motive_type, 0.6)

    # Defensive factor (TMM-based)
    tmm = _vehicle_tmm(unit)
    df = _defensive_factor(tmm)

    return subtotal * type_mod * df


def _vehicle_tmm(unit) -> int:
    """Vehicle TMM for defensive factor."""
    from ..utils.math import _tmm
    if unit.flank_mp == 0:
        return 0
    is_vtol = unit.motive_type == "VTOL"
    run_tmm = _tmm(unit.flank_mp, is_vtol)
    if unit.is_equipped_with("stealth"):
        run_tmm += 2
    return run_tmm


def _vehicle_offensive_br(unit) -> float:
    from ..models.data_store import DataStore
    from collections import defaultdict

    # Build weapon entries (no heat for vehicles)
    weapon_entries = []
    weapon_bv_by_ammo = defaultdict(float)
    for w in unit.weapons:
        try:
            wp = DataStore.weapon(w.weapon_key)
            base_bv = wp.bv
            if w.fcs in ("aiv", "av") and wp.useAmmo:
                base_bv *= 1.2
            if unit.is_equipped_with("tc") and wp.useTC:
                base_bv *= 1.25
            weapon_entries.append({"bv": base_bv, "heat": 0, "key": w.weapon_key, "ammo_type": wp.useAmmo})
            if wp.useAmmo:
                weapon_bv_by_ammo[wp.useAmmo] += base_bv
        except KeyError:
            continue

    ammo_bv = _calc_ammo_bv_generic(unit, weapon_bv_by_ammo)
    wbr = sum(w["bv"] for w in weapon_entries) + ammo_bv

    # Weight: tonnage / 2
    wbr += unit.tonnage / 2.0

    # Speed Factor from cruise MP
    sf = _speed_factor(unit.flank_mp, 0)
    return wbr * sf


# ═══════════════════════════════════════════════════════════════════════════════
# Battle Armor BV
# ═══════════════════════════════════════════════════════════════════════════════

_BA_FIRE_RESIST_ARMOR = {"bafireresist", "bareactive", "bareflective"}


def _calculate_ba_bv(unit) -> int:
    """Calculate BV 2.0 for a Battle Armor squad."""
    total = 0.0
    for _ in range(unit.squad_size):
        total += _ba_trooper_bv(unit)
    total *= (0.9 + 0.1 * unit.squad_size)
    return max(round(total), 1)


def _ba_trooper_bv(unit) -> float:
    from ..models.data_store import DataStore
    from collections import defaultdict

    # Defensive: armor × factor + 1 (warrior)
    armor_factor = 3.5 if any(unit.is_equipped_with(k) for k in _BA_FIRE_RESIST_ARMOR) else 2.5
    dbr = unit.armor_per_trooper * armor_factor + 1.0

    # Defensive equipment
    for e in unit.equipment:
        try:
            eq = DataStore.equipment(e.equipment_key)
        except KeyError:
            continue
        if e.equipment_key in ("improvedsensors", "probe", "ecm", "cecm"):
            dbr += 1
        elif e.equipment_key == "aecm":
            dbr += 2

    # Defensive factor
    tmm = _ba_tmm(unit)
    df = 1.0 + tmm / 10.0 + 0.1
    if unit.is_equipped_with("camosystem"):
        df += 0.2
    if unit.is_equipped_with("bastealth"):
        df += 0.2
    if unit.is_equipped_with("bamimetic"):
        df += 0.3
    dbr *= df

    # Offensive: all weapons full BV (BA weapon BVs are already per-weapon)
    # Note: true BA BV divides squad support weapons by squad size and
    # doubles energy weapons for anti-mek, but our BA weapon data uses
    # mech-scale BVs which don't match BA-scale values.
    weapon_bv_by_ammo = defaultdict(float)
    weapon_bv_sum = 0.0
    for w in unit.weapons:
        try:
            wp = DataStore.weapon(w.weapon_key)
        except KeyError:
            continue
        bv = wp.bv
        weapon_bv_sum += bv
        if wp.useAmmo:
            weapon_bv_by_ammo[wp.useAmmo] += bv

    ammo_bv = _calc_ammo_bv_generic(unit, weapon_bv_by_ammo)
    obr = weapon_bv_sum + ammo_bv

    # Speed factor
    mp = unit.ground_mp
    if unit.other_mp > mp:
        mp = unit.other_mp
    sf = _speed_factor(mp, 0)
    obr *= sf

    return dbr + obr


def _ba_tmm(unit) -> int:
    """BA TMM for defensive factor."""
    from ..utils.math import _tmm
    ground_tmm = _tmm(unit.ground_mp)
    if unit.other_mp > 0:
        other_tmm = _tmm(unit.other_mp, unit.other_motive_type == "VTOL")
        return max(ground_tmm, other_tmm)
    return ground_tmm


