# ── MUL BV Lookup Cache ────────────────────────────────────────────────────

_bv_lookup: dict[str, list] | None = None


def _load_bv_lookup() -> dict[str, list]:
    """Lazy-load BV lookup YAML. Returns {key: [bv, mul_id]}."""
    import os
    import yaml

    path = os.path.join(os.path.dirname(__file__), "..", "..", "data", "bv_lookup.yaml")
    with open(path, encoding="utf-8") as f:
        return yaml.safe_load(f)


def _lookup_bv(unit) -> int | None:
    """Return cached MUL BV if exact match, else None."""
    global _bv_lookup
    if _bv_lookup is None:
        _bv_lookup = _load_bv_lookup()
    key = f"{unit.chassis}|{unit.variant}|{unit.unit_type_label}".upper()
    entry = _bv_lookup.get(key)
    if entry is not None:
        return entry[0]
    return None


